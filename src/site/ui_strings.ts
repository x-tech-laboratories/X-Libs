// The frame's words for a language tag such as "pt-BR": the exact tag, then its language, then English, each filling
// what the one before lacks, with the site's own words over all of them.
export function messages_for(lang: string, own: Record<string, SiteMessages> = {}): Record<SiteMessageKey, string> {
  const language = lang.toLowerCase().split("-")[0];
  const tags = [lang, lang.toLowerCase(), language];
  const layers = [english, site_messages.en, own.en, ...tags.flatMap((tag) => [site_messages[tag], own[tag]])];
  return Object.assign({}, ...layers.filter(Boolean));
}
